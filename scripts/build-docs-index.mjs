#!/usr/bin/env node
// Generates docs/index.md — the landing page of the GitHub Pages docs site —
// from the markdown files actually present under docs/.
//
// Also stamps every docs/**/*.md with a minimal Jekyll front-matter block when
// one is missing: Jekyll only runs files WITH front matter through the
// markdown→HTML pipeline; without it they would be served as raw text.
// Stamping is idempotent (files already starting with `---` are untouched).
//
// Zero-dependency Node (>=18). Deterministic: same docs tree → same bytes.
//
// Usage:
//   node scripts/build-docs-index.mjs          # write docs/index.md + stamp FM
//   node scripts/build-docs-index.mjs --check  # exit 1 if index.md is stale
//
// The generated index.md is COMMITTED (not built in CI) so its diff is
// reviewable and the Pages workflow stays pure-Jekyll with no Node setup step.

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, basename, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DOCS = join(ROOT, 'docs');
const OUT = join(DOCS, 'index.md');
const REPO_URL = 'https://github.com/pgedeon/openclaw-project-webos';

/** Root-level docs grouped by filename; anything unmapped lands in "Other". */
const CATEGORIES = [
  {
    name: 'Getting Started',
    files: [
      'install-openclaw.md',
      'install-standalone.md',
      'development.md',
      'configuration-reference.md',
    ],
  },
  {
    name: 'User Documentation',
    files: [
      'user-guide.md',
      'views-reference.md',
      'widget-catalog.md',
      'admin-guide.md',
    ],
  },
  {
    name: 'API Reference',
    files: ['api.md', 'api-reference-complete.md', 'auth-reference.md', 'mcp-server.md'],
  },
  {
    name: 'Architecture & Internals',
    files: [
      'shell-architecture.md',
      'WIDGET-SYSTEM.md',
      'offline-reference.md',
      'storage-reference.md',
      'schema-reference.md',
      'dispatcher-monitor-reference.md',
      'DISPATCHER_V2_DESIGN.md',
      'AGENT_INTEGRATION.md',
      'memory-system.md',
      'file-explorer-notepad-implementation.md',
      'scripts-reference.md',
    ],
  },
];

/** Whole subdirectories become their own category. */
const SUBDIRS = [
  { dir: 'briefs', name: 'Design Briefs' },
  { dir: 'research', name: 'Research & Spikes' },
];

function listMarkdown(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listMarkdown(full));
    else if (entry.isFile() && entry.name.endsWith('.md')) out.push(full);
  }
  return out;
}

/** First `# Heading` in the file, else a prettified filename. */
function titleOf(rel) {
  try {
    const body = readFileSync(join(DOCS, rel), 'utf8').replace(/^---\n.*?\n---\n*/s, '');
    const m = body.match(/^#\s+(.+?)\s*$/m);
    if (m) return m[1].trim();
  } catch {
    /* fall through to filename */
  }
  return basename(rel).replace(/\.md$/, '').replace(/[-_]+/g, ' ');
}

/** Prepend Jekyll front matter to files that lack it. Returns # stamped. */
function stampFrontMatter(files) {
  let n = 0;
  for (const abs of files) {
    const src = readFileSync(abs, 'utf8');
    if (src.startsWith('---')) continue;
    writeFileSync(abs, '---\nlayout: default\n---\n\n' + src);
    n++;
  }
  return n;
}

const allAbs = listMarkdown(DOCS).filter((p) => p !== OUT);
const stamped = stampFrontMatter(allAbs);

const allRel = allAbs.map((p) => relative(DOCS, p).split('\\').join('/'));
const assigned = new Set();

function section(name, rels) {
  const rows = rels.filter((r) => !assigned.has(r));
  rows.forEach((r) => assigned.add(r));
  if (!rows.length) return '';
  const items = rows
    .sort()
    .map((r) => `- [${titleOf(r)}](${encodeURI(r)})`)
    .join('\n');
  return `## ${name}\n\n${items}\n`;
}

let md = `---
title: Documentation Index
---

# OpenClaw WebOS — Documentation Index

Complete documentation for the OpenClaw Project Dashboard ("WebOS"). Source lives in [docs/](${REPO_URL}/tree/main/docs); this page is generated by [scripts/build-docs-index.mjs](${REPO_URL}/blob/main/scripts/build-docs-index.mjs) and published automatically via GitHub Pages.

`;

for (const cat of CATEGORIES) {
  md += section(cat.name, cat.files);
}
for (const sub of SUBDIRS) {
  md += section(sub.name, allRel.filter((r) => r.startsWith(sub.dir + '/')));
}
md += section('Other', allRel);

md += `---

*Generated by \`scripts/build-docs-index.mjs\` — do not edit by hand; add or change docs under \`docs/\` and re-run it.*
`;

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== md) {
    console.error('docs/index.md is stale — re-run scripts/build-docs-index.mjs');
    process.exit(1);
  }
  console.log('docs/index.md up to date');
} else {
  writeFileSync(OUT, md);
  console.log(
    `docs/index.md written (${allRel.length} docs indexed, ${stamped} front-matter stamped)`,
  );
}
